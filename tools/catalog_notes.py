"""Regenerate docs/CATALOG_NOTES.md from `hyperframes catalog --json`.

Usage:  uv run tools/catalog_notes.py
Groups the registry by the categories the recipes care about.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hf  # noqa: E402
import studio_config as cfg  # noqa: E402

cfg.utf8_stdout()

# (heading, predicate on item) — an item can appear in several groups.
GROUPS = [
    ("Shader / GPU transitions", lambda i, t: "transition" in t and bool({"shader", "webgpu", "webgl", "webgpu-shader"} & t)),
    ("Other transitions", lambda i, t: ("transition" in t or "transition-primitive" in t) and not ({"shader", "webgpu", "webgl", "webgpu-shader"} & t)),
    ("Caption styles", lambda i, t: bool({"captions", "caption-style"} & t)),
    ("Typography / kinetic text", lambda i, t: bool({"typography", "text", "handwritten"} & t) and not ({"captions", "caption-style"} & t)),
    ("Title cards", lambda i, t: "title-card" in t),
    ("Lower thirds", lambda i, t: "lower-third" in t),
    ("Overlays & light leaks / textures", lambda i, t: bool({"overlay", "texture", "effect"} & t) or "leak" in i["name"]),
    ("Beat / music / audio-reactive", lambda i, t: any(k in (i["name"] + " " + i.get("description", "")).lower() for k in ("beat", "music", "audio-reactive", "waveform", "kick"))),
    ("Video primitives (footage handling)", lambda i, t: "video-primitive" in t),
    ("Camera moves", lambda i, t: "camera" in t),
    ("Backgrounds", lambda i, t: "background" in t),
    ("Images / galleries / carousels", lambda i, t: bool({"images", "gallery", "carousel"} & t)),
    ("Data / charts / maps", lambda i, t: bool({"data", "chart", "map"} & t)),
    ("3D", lambda i, t: "3d" in t),
    ("Vertical / social", lambda i, t: bool({"vertical", "social"} & t)),
]


def main() -> int:
    p = subprocess.run(hf.hf_cmd() + ["catalog", "--json"], env=hf.hf_env(),
                       capture_output=True, text=True, encoding="utf-8")
    items = json.loads(p.stdout)
    ver = subprocess.run(hf.hf_cmd() + ["--version"], env=hf.hf_env(), capture_output=True,
                         text=True).stdout.strip()
    out = [f"# HyperFrames catalog notes\n",
           f"Generated by `uv run tools/catalog_notes.py` from HyperFrames {ver}: "
           f"{len(items)} items ({sum(i['type'] == 'block' for i in items)} blocks, "
           f"{sum(i['type'] == 'component' for i in items)} components).\n",
           "Install one into a project with `uv run tools/hf.py add <name>` (run inside the project). "
           "Search by meaning: `uv run tools/hf.py catalog <words>`.\n"]
    for title, pred in GROUPS:
        sel = [i for i in items if pred(i, set(i.get("tags", [])))]
        if not sel:
            continue
        out.append(f"\n## {title} ({len(sel)})\n")
        out.append("| name | type | what it is |\n|---|---|---|")
        for i in sorted(sel, key=lambda x: x["name"]):
            d = " ".join(i.get("description", "").split())
            d = (d[:157] + "…") if len(d) > 160 else d
            out.append(f"| `{i['name']}` | {i['type']} | {d.replace('|', '/')} |")
    dest = cfg.ROOT / "docs" / "CATALOG_NOTES.md"
    dest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {dest} ({len(items)} items)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
